package com.amazon.login;

public class Teacher extends details {
	
	private String techname;
	private String techaddress;
	private String techSalary;
	private String techposition;
	
	public String getTechname() {
		return techname;
	}
	public void setTechname(String techname) {
		this.techname = techname;
	}
	public String getTechaddress() {
		return techaddress;
	}
	public void setTechaddress(String techaddress) {
		this.techaddress = techaddress;
	}
	public String getTechSalary() {
		return techSalary;
	}
	public void setTechSalary(String techSalary) {
		this.techSalary = techSalary;
	}
	public String getTechposition() {
		return techposition;
	}
	public void setTechposition(String techposition) {
		this.techposition = techposition;
	}
	
	
}
